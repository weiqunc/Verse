// 生成歌曲詳細資訊區塊
function generateSongMeta(item) {
  const metaItems = [];

  // 作詞
  if (item.lyricist && item.lyricist.length > 0) {
    metaItems.push({
      label: "作詞",
      value: Array.isArray(item.lyricist)
        ? item.lyricist.join(", ")
        : item.lyricist
    });
  }

  // 作曲
  if (item.composer && item.composer.length > 0) {
    metaItems.push({
      label: "作曲",
      value: Array.isArray(item.composer)
        ? item.composer.join(", ")
        : item.composer
    });
  }

  if (item.original_artist && item.original_artist.length > 0) {
    metaItems.push({
      label: "原唱",
      value: Array.isArray(item.original_artist)
        ? item.original_artist.join(", ")
        : item.original_artist
    });
  }

  // 專輯
  if (item.albums) {
    metaItems.push({
      label: "專輯",
      value: item.albums
    });
  }

  // 發行日期
  if (item.release_date) {
    metaItems.push({
      label: "發行日期",
      value: item.release_date
    });
  }

  // 語言
  if (item.language) {
    metaItems.push({
      label: "語言",
      value: item.language
    });
  }

  // 風格
  if (item.genre) {
    metaItems.push({
      label: "風格",
      value: item.genre
    });
  }

  if (item.rating) {
    const ratingNum = parseInt(item.rating) || 0;
    let stars = "";
    for (let i = 1; i <= 5; i++) {
      if (i <= ratingNum) {
        stars += "⭐";
      } else {
        stars += "☆";
      }
    }
    metaItems.push({
      label: "評分",
      value: `${stars} (${ratingNum}/5)`
    });
  }

  // 如果沒有任何資訊，回傳空字串
  if (metaItems.length === 0) {
    return "";
  }

  // 生成 HTML
  return `
    <div class="song-detail-meta">
      ${metaItems
        .map(
          (meta) => `
        <div class="meta-row">
          <span class="meta-label">${meta.label}:</span>
          <span class="meta-value">${meta.value}</span>
        </div>
      `
        )
        .join("")}
    </div>
  `;
}

