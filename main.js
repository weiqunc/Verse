function showFavoriteDetail(favoriteId) {
  const favorite = favorites.find((f) => f.id === favoriteId);
  if (!favorite) return;

  // 找到相關的歌曲
  const relatedSong = songs.find((s) => s.id === favorite.songId);

  if (relatedSong) {
    // 如果找到相關歌曲，跳轉到歌曲詳細頁面
    showSongDetail(relatedSong.id, "song");
  } else {
    // 如果沒找到相關歌曲，跳轉到收藏頁面
    showPage("favorites");
  }
}

