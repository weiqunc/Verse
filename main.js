// 提取所有歌手及其歌曲數量
function getArtists() {
  const artistMap = new Map();

  songs.forEach((song) => {
    if (!song || !song.creators) return;

    song.creators.forEach((creator) => {
      const name = creator.trim();
      if (name) {
        if (!artistMap.has(name)) {
          artistMap.set(name, {
            name: name,
            count: 0,
            songs: []
          });
        }
        const artist = artistMap.get(name);
        artist.count++;
        artist.songs.push(song);
      }
    });
  });

  return Array.from(artistMap.values());
}

// 渲染歌手清單
function renderArtists() {
  const artistGrid = document.getElementById("artistGrid");
  if (!artistGrid) return;

  let artists = getArtists();

  // 取得排序方式
  const sortBy = document.getElementById("artistSort")?.value || "count";

  if (sortBy === "count") {
    artists.sort((a, b) => b.count - a.count);
  } else {
    artists.sort((a, b) => a.name.localeCompare(b.name, "zh-TW"));
  }

  artistGrid.innerHTML = artists
    .map((artist) => {
      // 取得歌手名字的第一個字作為頭像
      const initial = artist.name.charAt(0);

      return `
      <div class="artist-card" onclick="showArtistDetail('${artist.name.replace(
        /'/g,
        "\\'"
      )}')">
        <div class="artist-card-avatar">${initial}</div>
        <div class="artist-card-name">${artist.name}</div>
        <div class="artist-card-count">${artist.count} 首歌曲</div>
      </div>
    `;
    })
    .join("");
}

